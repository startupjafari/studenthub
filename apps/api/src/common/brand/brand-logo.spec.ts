import { brandLogoPng } from './brand-logo'

// Проверяем ветку деградации: sharp опирается на librsvg, и в урезанном образе
// растеризация может не завестись. Документ без логотипа остаётся годным, упавшая
// выгрузка — нет, поэтому brandLogoPng обязан вернуть null, а не бросить.
//
// Настоящая отрисовка здесь не проверяется намеренно: поднимать sharp в юнит-тесте
// дорого (см. тот же приём в rooms/room-qr.service.spec.ts), а результат — картинка,
// которую всё равно оценивают глазами. Он проверен прогоном: оба варианта знака
// отрисовались в PNG.
jest.mock('sharp', () => ({
  __esModule: true,
  default: () => {
    throw new Error('librsvg отсутствует')
  },
}))

describe('brandLogoPng', () => {
  it('возвращает null, если отрисовать знак не удалось', async () => {
    await expect(brandLogoPng(96)).resolves.toBeNull()
  })
})
