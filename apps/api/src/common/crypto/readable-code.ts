import { randomInt } from 'node:crypto'

/**
 * Код, который человек читает с бумаги и набирает руками.
 *
 * Алфавит без визуально похожих символов: нет 0/O, 1/I/L — их путают при наборе с
 * наклейки или с колонтитула распечатанного документа. 31 символ на позицию, 8 позиций —
 * около 8·10^11 вариантов; коллизии ловит unique-индекс в базе, а не проверка в коде.
 *
 * Жил в `rooms/room-code.ts` для кода помещения. Переехал сюда, когда такой же код
 * понадобился журналу выгрузок: два генератора «человекочитаемых кодов» в одном проекте
 * разойдутся alphabet'ом, и одинаково выглядящие коды окажутся из разных пространств.
 */
const ALPHABET = '23456789ABCDEFGHJKMNPQRSTUVWXYZ'

export function readableCode(length = 8): string {
  let code = ''
  for (let i = 0; i < length; i += 1) {
    code += ALPHABET[randomInt(ALPHABET.length)]
  }
  return code
}
