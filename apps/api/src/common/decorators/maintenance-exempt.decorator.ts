import { SetMetadata } from '@nestjs/common'

export const MAINTENANCE_EXEMPT_KEY = 'maintenanceExempt'

/**
 * Маршрут продолжает работать во время техработ.
 *
 * Список исключений — это список того, без чего режим НЕЛЬЗЯ СНЯТЬ. Ошибка здесь стоит
 * дорого в одну сторону: забыть исключение значит запереть платформу так, что вернуть её
 * можно будет только из базы руками. Поэтому исключения ставятся на весь контроллер, а не
 * на отдельные ручки, — чтобы новая ручка входа или мини-аппа получала их автоматически.
 *
 * Сейчас исключены: вход (`/auth`), мини-апп (`/mini`), состояние платформы (`/platform`)
 * и живость (`/health` — без неё Railway решит, что контейнер умер, и перезапустит его
 * по кругу).
 */
export const MaintenanceExempt = () => SetMetadata(MAINTENANCE_EXEMPT_KEY, true)
