import { SetMetadata } from '@nestjs/common'

export const MINI_ALLOWED_KEY = 'miniAllowed'

/**
 * Разрешает маршрут токену админского мини-аппа (Telegram).
 *
 * Белый список выражен именно так — пометками на маршрутах, а не списком путей в одном
 * файле: список путей расходится с кодом молча, а пометка живёт рядом с обработчиком и
 * видна на ревью. Что доступно с телефона, выясняется одним грепом по декоратору.
 *
 * По умолчанию не разрешено ничего: MiniAppGuard отклоняет токен мини-аппа на любом
 * непомеченном маршруте, даже если роль в вебе это позволяет. Потерянный телефон не
 * должен означать потерянную платформу.
 */
export const MiniAllowed = () => SetMetadata(MINI_ALLOWED_KEY, true)
