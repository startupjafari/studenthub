import { SetMetadata } from '@nestjs/common'

export const REQUIRES_CONFIRMATION_KEY = 'requiresConfirmation'

/** Нужно ли подтверждение для конкретного запроса. `true` — всегда. */
export type ConfirmationRule = true | ((body: Record<string, unknown>) => boolean)

/**
 * Действие требует подтверждения вторым фактором, когда его совершают ИЗ МИНИ-АППА.
 *
 * Почему только оттуда: в вебе человек уже прошёл пароль и 2FA в этой же сессии, а
 * мини-апп открывается одним касанием на разблокированном телефоне — потерянный или
 * отданный на минуту аппарат иначе даёт полный доступ к модерации без единого вопроса.
 *
 * Необязательный предикат нужен маршрутам, где разрушительно не всякое обращение:
 * решение по жалобе может и заблокировать человека, и просто отклонить жалобу, и
 * спрашивать код во втором случае значило бы приучить вводить его не глядя.
 *
 * Проверку делает ActionConfirmGuard, а не сервис: так требование ставится декоратором и
 * не тянет TwoFactorService в домены, которые о нём знать не должны.
 */
export const RequiresConfirmation = (rule: ConfirmationRule = true) =>
  SetMetadata(REQUIRES_CONFIRMATION_KEY, rule)
