import { SetMetadata } from '@nestjs/common'

export const SECURITY_ALLOWED_KEY = 'securityAllowed'

/**
 * Разрешает маршрут роли охранника (SECURITY_GUARD, docs/PROJECT.md §2).
 *
 * Охране открыт только явный список: вход и свой аккаунт, уведомления, проверка
 * студенческого, помещения, камеры. Остальное SecurityRoleGuard закрывает `403` — в том
 * числе эндпоинты без `@Roles`, которые по общему правилу открыты любому вошедшему, а в
 * сервисах отдают незнакомой роли данные уровня «весь вуз» (группы, расписание,
 * материалы). Запрет по умолчанию закрывает и маршруты, которых ещё нет.
 *
 * Пометка ставится на обработчик или на весь контроллер. Что доступно охране, выясняется
 * одним грепом по декоратору — тем же приёмом, что `@MiniAllowed()`.
 */
export const SecurityAllowed = () => SetMetadata(SECURITY_ALLOWED_KEY, true)
