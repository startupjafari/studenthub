import type { OpsEventName } from './ops-event.registry'

// Порт служебных уведомлений (docs/TELEGRAM_BOT.md §4.1). Доменные модули знают ТОЛЬКО
// этот интерфейс: `CronMonitorService`, health и процессоры очередей не должны знать,
// что на другом конце Telegram. Замена транспорта (Slack, почта, вебхук) — новая
// реализация того же порта, без единой правки в доменных модулях.

/** Данные события: только идентификаторы, счётчики и технические строки — никаких ПД (§0.1). */
export type OpsEventData = Record<string, string | number>

export interface OpsNotifier {
  /**
   * Сообщает факт. Решение «отправлять ли» принимает политика (§7.1.4), доставка
   * асинхронная — вызывающий код не ждёт сети и не получает ошибок: сбой отправки
   * не влияет на приложение (§0.1.3).
   */
  emit(event: OpsEventName, data?: OpsEventData): void
}

// Токен DI живёт здесь же: файл не импортирует ни одного провайдера, поэтому цикла,
// из-за которого пришлось выносить REDIS_CLIENT в отдельный файл, тут не возникает.
export const OPS_NOTIFIER = Symbol('OPS_NOTIFIER')
