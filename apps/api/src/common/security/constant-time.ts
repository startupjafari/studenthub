import { timingSafeEqual } from 'node:crypto'

/**
 * Сравнение секретов за постоянное время.
 *
 * Обычный `===` для строк прекращает сравнение на первом несовпавшем байте, то есть время
 * ответа зависит от длины совпавшего префикса. Для секрета, который подбирают снаружи, это
 * канал утечки: перебирая байт за байтом и глядя на время, секрет восстанавливают целиком,
 * не зная его. По сети шум измерений велик и атака трудна, но цена защиты здесь нулевая, а
 * рассуждение «в нашем случае не подберут» — ровно то, на чём такие вещи и ломаются.
 *
 * Длину `timingSafeEqual` скрыть не может (буферы разной длины он просто не принимает), и
 * это нормально: длина секрета не тайна.
 */
export function equalsConstantTime(a: string, b: string): boolean {
  const left = Buffer.from(a, 'utf8')
  const right = Buffer.from(b, 'utf8')
  if (left.length !== right.length) return false
  return timingSafeEqual(left, right)
}
