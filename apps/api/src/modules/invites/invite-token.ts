import { createHash } from 'node:crypto'

/**
 * Токен инвайта хранится в БД ХЭШЕМ, а не как есть.
 *
 * Сам токен — это право зарегистрироваться с заданной ролью и scope. Пока он лежал в
 * колонке открытым текстом, любой доступ на чтение к базе (бэкап, реплика, выгрузка для
 * отладки) превращался в возможность завести учётку от чужого приглашения — в том числе
 * с ролью декана или админа вуза.
 *
 * sha256 без соли — намеренно: токен это 122 бита из `randomUUID()`, перебирать там нечего,
 * а поиск обязан оставаться одним запросом по уникальному индексу. Для паролей так нельзя,
 * для случайного токена — ровно то, что нужно.
 */
export function hashInviteToken(raw: string): string {
  return createHash('sha256').update(raw).digest('hex')
}

/**
 * Значения, по которым ищем инвайт: сначала хэш, следом сам токен.
 *
 * Второе — фолбэк для строк, записанных открытым текстом. Приглашения, выданные до хэширования,
 * давно истекли (инвайт живёт TTL.INVITE_HOURS — 48 часов), но открытые токены до сих пор
 * пишут сиды: dev-инвайт админа вуза (prisma/seed.mjs), e2e-фикстура (prisma/e2e-fixture.mjs,
 * на нём стоит apps/web/e2e/register.e2e.ts) и демо-инвайты мега-сида. Убирать фолбэк — вместе
 * с переводом сидов на hashInviteToken, иначе ссылка /register?token=… из сида перестанет работать.
 */
export function inviteTokenLookups(raw: string): string[] {
  // Строку вида sha256 (64 hex) по открытому значению не ищем: это формат самих хэшей в
  // колонке, и иначе хэш, прочитанный из бэкапа или реплики, проходил как токен — поиск
  // находил строку по равенству. Настоящие токены (UUID, токены сида) так не выглядят.
  return SHA256_HEX.test(raw) ? [hashInviteToken(raw)] : [hashInviteToken(raw), raw]
}

const SHA256_HEX = /^[0-9a-f]{64}$/i
