import { createHash } from 'node:crypto'

/**
 * Токен инвайта хранится в БД ХЭШЕМ, а не как есть.
 *
 * Сам токен — это право зарегистрироваться с заданной ролью и scope. Пока он лежал в
 * колонке открытым текстом, любой доступ на чтение к базе (бэкап, реплика, выгрузка для
 * отладки) превращался в возможность завести учётку от чужого приглашения — в том числе
 * с ролью декана или админа вуза.
 *
 * sha256 без соли — намеренно: токен это 122 бита из `randomUUID()`, перебирать там нечего,
 * а поиск обязан оставаться одним запросом по уникальному индексу. Для паролей так нельзя,
 * для случайного токена — ровно то, что нужно.
 */
export function hashInviteToken(raw: string): string {
  return createHash('sha256').update(raw).digest('hex')
}

/**
 * Значения, по которым ищем инвайт: сначала хэш, следом сам токен.
 *
 * Второе — переходный фолбэк для приглашений, выданных до этой правки: они лежат в базе
 * открытым текстом, и без фолбэка перестали бы работать разом, вместе со ссылками в уже
 * отправленных письмах. Инвайт живёт 30 дней (TTL.INVITE_HOURS), так что через месяц после
 * выката таких строк не останется и фолбэк нужно убрать — вместе с этим комментарием.
 */
export function inviteTokenLookups(raw: string): string[] {
  return [hashInviteToken(raw), raw]
}
