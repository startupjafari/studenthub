import Foundation

/// Правило движения позиции догона (`ChatRecord.syncSeq`, IOS_RULES 9.3.2).
///
/// `seq` в чате растёт на 1 за сообщение. Позиция значит «до этого номера переписка в
/// базе непрерывна», поэтому двигается только тем, что к ней примыкает. Сообщение через
/// разрыв сохраняется, но позицию не двигает: иначе следующий догон пошёл бы от него, и
/// пропущенное между осталось бы пропущенным навсегда. Ложная тревога (номер съели
/// удалённые или скрытые) стоит одного пустого `GET …/updates` — это дешевле потери.
enum SyncPosition {
    enum Step: Equatable {
        /// Ничего нового сверх позиции.
        case stay
        /// Непрерывное продолжение — позиция встаёт на новый номер.
        case advance(to: Int)
        /// Между позицией и пришедшим есть пропуск — нужен догон с прежней позиции.
        case gap
    }

    /// `seqs` — номера одного непрерывного куска (сообщение сокета, страница истории).
    /// `isHead` — кусок заведомо доходит до свежего (последняя страница истории): у ни
    /// разу не сверенного чата (`position == 0`) с него сверка и начинается, а старее —
    /// это история, её дочитает прокрутка вверх.
    static func step(from position: Int, seqs: [Int], isHead: Bool = false) -> Step {
        guard let low = seqs.min(), let high = seqs.max(), high > position else { return .stay }
        if low <= position + 1 || (isHead && position == 0) {
            return .advance(to: high)
        }
        return .gap
    }
}
