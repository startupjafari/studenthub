import { useEffect, useRef } from 'react'
import { webApp } from '../telegram/webapp'

// Возврат — один на всё приложение.
//
// Кнопка у него тоже одна: своей стрелки в шапке экрана нет, возврат живёт в клиенте
// (`BackButton` Telegram). Раньше каждый экран сам её показывал и прятал, и на верхних
// экранах она пропадала — а с ней пропадал и единственный видимый выход. В полноэкранном
// режиме крестик Telegram висит поверх приложения и находится не сразу, и человек
// оставался на экране, с которого, на его взгляд, деться некуда.
//
// Поэтому кнопка видна ВСЕГДА, а решает она на месте: есть куда вернуться — возвращаемся,
// некуда — закрываем мини-апп. Так же ведёт себя Wallet, и так же устроена стрелка в
// родных приложениях: с первого экрана она выводит наружу.
//
// Стек, а не флаг: экраны вкладываются (очередь → жалоба, обращение → переписка), и знать,
// «есть ли куда назад», обязан не каждый из них, а само приложение.

interface Slot {
  run: () => void
}

const stack: Slot[] = []

/**
 * Экран объявляет, куда ведёт возврат с него. Снимается сам, когда экран уходит, —
 * поэтому забыть «выключить» возврат невозможно, а именно так он и терялся раньше.
 *
 * Обработчик читается через ref: он пересобирается на каждом рендере экрана, и держать
 * его в зависимостях эффекта значило бы переписывать стек по десять раз за переход.
 */
export function useBackHandler(onBack: () => void): void {
  const latest = useRef(onBack)
  latest.current = onBack

  useEffect(() => {
    const slot: Slot = { run: () => latest.current() }
    stack.push(slot)
    return () => {
      const at = stack.indexOf(slot)
      if (at >= 0) stack.splice(at, 1)
    }
  }, [])
}

/**
 * Назад — или из приложения, если возвращаться некуда.
 *
 * Берётся ВЕРХНИЙ обработчик стека: он принадлежит самому глубокому из открытых экранов,
 * а он и есть тот, с которого уходят.
 */
export function goBack(): void {
  const top = stack.at(-1)
  if (top) {
    top.run()
    return
  }
  webApp()?.close()
}
