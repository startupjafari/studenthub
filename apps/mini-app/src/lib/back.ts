import { useEffect, useRef, useSyncExternalStore } from 'react'
import { webApp } from '../telegram/webapp'

// Возврат — один на всё приложение.
//
// Кнопка у него тоже одна: своей стрелки в шапке экрана нет, возврат живёт в клиенте
// (`BackButton` Telegram). Раньше каждый экран сам её показывал и прятал, и делал это
// вразнобой.
//
// Ключевое здесь — КОГДА её не показывать. Telegram рисует в своей шапке «Закрыть», пока
// мини-апп не попросил кнопку возврата, и заменяет надпись на «‹ Назад», как только
// попросил. Значит, показанная на верхнем экране стрелка отнимает у человека выход:
// «Назад» с первого экрана вести некуда, а «Закрыть» уже не видно. Отсюда правило: есть
// открытый вглубь экран — просим стрелку, нет — молчим, и клиент сам показывает «Закрыть».
// Так же ведёт себя Wallet.
//
// Стек, а не флаг: экраны вкладываются (очередь → жалоба, обращение → переписка), и знать,
// «есть ли куда назад», обязан не каждый из них, а само приложение.

interface Slot {
  run: () => void
}

const stack: Slot[] = []
const listeners = new Set<() => void>()

function notify(): void {
  for (const listener of listeners) listener()
}

/**
 * Экран объявляет, куда ведёт возврат с него. Снимается сам, когда экран уходит, —
 * поэтому забыть «выключить» возврат невозможно, а именно так он и терялся раньше.
 *
 * Обработчик читается через ref: он пересобирается на каждом рендере экрана, и держать
 * его в зависимостях эффекта значило бы переписывать стек по десять раз за переход.
 */
export function useBackHandler(onBack: () => void): void {
  const latest = useRef(onBack)
  latest.current = onBack

  useEffect(() => {
    const slot: Slot = { run: () => latest.current() }
    stack.push(slot)
    notify()
    return () => {
      const at = stack.indexOf(slot)
      if (at >= 0) stack.splice(at, 1)
      notify()
    }
  }, [])
}

/**
 * Есть ли куда возвращаться. По этому приложение решает, просить у клиента стрелку или
 * оставить его «Закрыть».
 *
 * `useSyncExternalStore`, потому что стек живёт вне React: его правят эффекты чужих
 * экранов, и узнать об этом иначе, чем подпиской, приложению неоткуда. Значение на сервере
 * не считается — мини-апп рисуется только в браузере, но третий аргумент обязателен.
 */
export function useCanGoBack(): boolean {
  return useSyncExternalStore(
    (listener) => {
      listeners.add(listener)
      return () => listeners.delete(listener)
    },
    () => stack.length > 0,
    () => false,
  )
}

/**
 * Назад — или из приложения, если возвращаться некуда.
 *
 * Берётся ВЕРХНИЙ обработчик стека: он принадлежит самому глубокому из открытых экранов,
 * а он и есть тот, с которого уходят.
 *
 * Выход здесь — страховка, а не основной путь: на верхнем экране стрелки нет вовсе, и
 * закрывает мини-апп «Закрыть» самого Telegram. Но между уходом последнего экрана и
 * ответом клиента на «спрячь кнопку» проходит кадр, и нажатие в этот кадр не должно
 * упереться в тишину.
 */
export function goBack(): void {
  const top = stack.at(-1)
  if (top) {
    top.run()
    return
  }
  webApp()?.close()
}
