import { useEffect } from 'react'

// Оболочка мини-аппа: панель разделов и место, которое она отнимает у содержимого.
//
// Панель нарисована в app.tsx и висит над всеми экранами — так и должно быть, пока
// экран принадлежит разделу. Но переписка с человеком разделу не принадлежит: из чужого
// разговора выходят назад, к обращению, а не в соседнюю вкладку, и панель внизу там
// отнимает место у поля ответа, ничего не предлагая взамен.
//
// Через класс на <body>, а не через контекст: убрать нужно чужой узел, стоящий выше по
// дереву, и место под него тоже резервирует не этот экран, а оболочка (styles.css).

/**
 * Экран во весь рост: на время его жизни панель разделов уходит, а высоту, которую под
 * неё резервировало содержимое, забирает сам экран.
 */
export function useFullScreen(): void {
  useEffect(() => {
    document.body.classList.add('full-screen')
    return () => document.body.classList.remove('full-screen')
  }, [])
}
