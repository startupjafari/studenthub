// Снятие заставки запуска.
//
// Полотно приходит вместе с разметкой (index.html): оно обязано быть на экране в первой
// же отрисовке, иначе человек увидит сначала приложение, а потом накрывающую его
// заставку — ровно наоборот. Отсюда и снятие живёт здесь, а не в компоненте: убирать
// нужно чужой узел, которого React не знает.
//
// Заставка уходит по готовности приложения, а не по расписанию, как на сайте: за ней
// прячется обмен initData на токен, и полотно, ушедшее раньше ответа, обнажило бы пустой
// экран «проверяем доступ» — то самое, ради чего заставка и заводилась.

/**
 * Сколько заставка держится минимум.
 *
 * Обмен занимает доли секунды, и без нижней границы марка успевала бы только моргнуть —
 * вспышка вместо заставки читается как сбой отрисовки. Столько же идёт разгорание ореола
 * на сайте, так что заставка уходит ровно тогда, когда свет дошёл до края.
 */
const MIN_MS = 1400

/** Длительность ухода полотна — та же, что в анимации `splash-out` (index.html). */
const FADE_MS = 300

let done = false

export function hideSplash(): void {
  // Экран доступа может смениться не один раз (привязка → готово): снимаем один раз.
  if (done) return
  done = true

  const splash = document.getElementById('splash')
  if (!splash) return

  // performance.now() отсчитывается от начала навигации, то есть от того момента, когда
  // полотно и появилось на экране, — отдельная отметка времени для этого не нужна.
  const wait = Math.max(0, MIN_MS - performance.now())
  window.setTimeout(() => {
    splash.className = 'gone'
    // Узел убирается после ухода: `visibility: hidden` оставляет его в дереве, а он лежит
    // поверх всего экрана и в старых WebView продолжает ловить касания.
    window.setTimeout(() => splash.remove(), FADE_MS)
  }, wait)
}
