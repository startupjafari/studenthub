/** Разбор списка из переменной окружения: `a,b, c` → ['a','b','c']. */
function parseList(raw: string | undefined): string[] | null {
  if (!raw) return null
  const items = raw
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean)
  return items.length > 0 ? items : null
}

