/**
 * Перезагружать страницу на каждой ширине вместо изменения размера окна.
 *
 * По умолчанию выключено: страница открывается один раз, дальше окно ресайзится. Так прогон
 * идёт в разы быстрее и, что важнее, не долбит API семикратным набором запросов — глобальный
 * throttler (100 запросов / 60 с с IP) при перезагрузке на каждой ширине начинает отдавать 429,
 * и отчёт заполняется сетевыми «ошибками», которых в жизни нет. Раскладка в приложении
 * определяется CSS-медиазапросами, поэтому ресайз даёт ту же картину. Включать флаг стоит,
 * когда подозрение падает на компонент, читающий ширину окна один раз при монтировании.
 */
export const RELOAD_PER_VIEWPORT = process.env.UI_AUDIT_RELOAD_PER_VIEWPORT === '1'

/** Скриншот всей страницы, а не только видимой части. Тяжелее и менее стабилен для сравнения. */
export const FULL_PAGE_SHOTS = process.env.UI_AUDIT_FULL_PAGE === '1'

