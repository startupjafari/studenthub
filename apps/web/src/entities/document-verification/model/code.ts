/**
 * Код из бланка в том виде, в каком его ищет сервер.
 *
 * Код переписывают руками с бумаги: с пробелами и дефисами для удобства чтения, строчными
 * буквами. Сервер сам приводит регистр, но разделители не убирает — поэтому чистим здесь,
 * иначе «abcd efgh» с бланка давал бы «Документ не найден».
 */
export function normalizeVerificationCode(raw: string): string {
  return raw.replace(/[\s-]+/g, '').toUpperCase()
}
