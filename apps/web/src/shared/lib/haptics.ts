'use client'

// Тактильная обратная связь (apple-design §13).
//
// Три правила, из которых здесь следует вся сдержанность:
//  1. Причинность — тик срабатывает на самом событии (строка защёлкнулась, порог пройден),
//     а не «после успешного запроса»: рука связывает ощущение с тем, что видит сейчас.
//  2. Согласованность — тик и кадр должны совпасть. Поэтому вызываем его синхронно с
//     изменением transform, а не в колбэке анимации и не после ответа сервера.
//  3. Уместность — только значимые моменты. Тик на каждое касание обучает его игнорировать,
//     и тогда он не работает и там, где нужен. Поэтому наружу — ровно две силы.
//
// Vibration API есть не везде (в Safari на iOS его нет вовсе), поэтому это всегда
// дополнение к визуальному отклику, никогда не замена.

/** Порог пройден, элемент защёлкнулся — самое частое и самое лёгкое ощущение. */
export function hapticTick(): void {
  vibrate(8)
}

/** Действие свершилось и его непросто отменить: удаление, отправка запроса, отказ. */
export function hapticCommit(): void {
  vibrate([12, 24, 12])
}

function vibrate(pattern: number | number[]): void {
  if (typeof navigator === 'undefined' || !('vibrate' in navigator)) return
  try {
    navigator.vibrate(pattern)
  } catch {
    // Вибрация запрещена политикой страницы или устройством — это не ошибка сценария.
  }
}
