// Устойчивый идентификатор для элементов редактируемого списка (варианты опроса,
// позиции запроса документов и т.п.).
//
// Зачем: такие списки правятся и удаляются по индексу, а `key={index}` запрещён
// (FRONTEND_RULES §15 п. 9) не из формализма — React переиспользует узел по позиции,
// и после удаления среднего элемента фокус, позиция курсора и состояние IME остаются
// на чужой строке.
//
// Почему счётчик, а не crypto.randomUUID(): id нужен только внутри одной страницы, а
// счётчик не зависит от secure context и не даёт разных значений на сервере и клиенте
// при SSR.
let sequence = 0

export function localId(prefix = 'item'): string {
  sequence += 1
  return `${prefix}-${sequence}`
}
