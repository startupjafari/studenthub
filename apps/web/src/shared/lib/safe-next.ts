/**
 * Куда разрешено вести параметр `next` после входа.
 *
 * Только относительный путь этого приложения: абсолютный URL или `//host` превратили бы
 * параметр в открытый редирект (ссылка на наш логин → увод на чужой сайт после входа).
 *
 * Используется и в middleware (проставляет параметр), и в форме логина (читает его),
 * поэтому живёт в shared: правило защиты одно на оба места.
 */
export function safeNextPath(value: string | null): string | null {
  if (!value || !value.startsWith('/') || value.startsWith('//')) return null
  return value
}
