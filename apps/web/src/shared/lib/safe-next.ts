/**
 * Куда разрешено вести параметр `next` после входа.
 *
 * Только относительный путь этого приложения: абсолютный URL или `//host` превратили бы
 * параметр в открытый редирект (ссылка на наш логин → увод на чужой сайт после входа).
 *
 * Обратный слэш запрещён наравне с прямым, и это не педантизм: в разборе URL по стандарту
 * WHATWG `\` в схемах http(s) эквивалентен `/`, поэтому `new URL('/\evil.com', origin)`
 * даёт `https://evil.com/`. Проверки одного только `//` тут мало — `/\evil.com` её
 * проходил, и форма логина уводила на чужой домен сразу после успешного входа.
 *
 * Управляющие символы (в т.ч. таб и перевод строки) отбрасываем тоже: разборщик URL
 * вырезает их молча, и `/\tevil` мог бы собраться во что-то, чего в проверке не было.
 *
 * Используется и в middleware (проставляет параметр), и в форме логина (читает его),
 * поэтому живёт в shared: правило защиты одно на оба места.
 */
export function safeNextPath(value: string | null): string | null {
  if (!value || !value.startsWith('/')) return null
  // eslint-disable-next-line no-control-regex -- ровно их и ищем: URL-разборщик их вырезает
  if (/[\u0000-\u001f\u007f]/.test(value)) return null
  // `//host` — протокол-относительный адрес; `\` запрещаем везде, а не только вторым
  // символом: разборщик URL приводит его к `/`, так что `/x/\evil.com` тоже уводит наружу.
  if (value.startsWith('//') || value.includes('\\')) return null
  return value
}
