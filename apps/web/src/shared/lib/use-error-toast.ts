'use client'

import { useCallback, useEffect } from 'react'
import { useTranslations } from 'next-intl'
import { toast } from 'sonner'
import { toApiError } from './api-error'

/**
 * Серверная ошибка МОДАЛЬНОЙ формы: уходит тостом в правый нижний угол, а не
 * алертом в шапке окна (DESIGN_SYSTEM §9 — то же исключение, что у входа).
 *
 * Причина: алерт внутри окна раздвигает его сверху, и поля с кнопками уезжают
 * из-под курсора ровно в момент повторной попытки; на невысоком экране окно вдобавок
 * упирается в 90vh и начинает прокручиваться, унося сообщение из вида. У формы на
 * СТРАНИЦЕ этой проблемы нет — там остаётся `FormAlert` (см. `useFormAlert`).
 *
 * `id` — свой у каждой формы: повторный отказ обновляет тот же тост, а не копит
 * стопку одинаковых сообщений.
 */
export function useErrorToast(id: string): { show: (error: unknown) => void } {
  const tErr = useTranslations('Errors')

  const show = useCallback(
    (e: unknown) => {
      const api = toApiError(e)
      // Поля из details показываем строкой под заголовком: у модальной формы их
      // немного, а подписывать ошибку под каждым полем тост не может.
      const details = api.code === 'VALIDATION_ERROR' ? api.details : undefined
      toast.error(tErr(api.code), {
        id,
        description: details?.length ? details.map((d) => d.message).join(' · ') : undefined,
      })
    },
    [id, tErr],
  )

  // Тост живёт ровно столько, сколько форма: окно закрыли — сообщение о его ошибке
  // уносим следом, иначе оно висит поверх экрана, к которому уже не относится.
  //
  // Гасить тост ПЕРЕД новой попыткой при этом нельзя: sonner помечает закрытый тост
  // на удаление и размонтирует через 200 мс, и ответ сервера, пришедший внутри этого
  // окна, обновит уже помеченную запись — отказ молча не покажется. Поэтому чистка
  // только здесь, при размонтировании, где новой ошибки заведомо не будет.
  useEffect(
    () => () => {
      // Тело блоком, а не сокращённой стрелкой: `toast.dismiss` возвращает id, и React
      // принял бы его за функцию очистки.
      toast.dismiss(id)
    },
    [id],
  )

  return { show }
}
