// Суточный профиль по сетке «день недели × час» — чистые функции, отдельно от панели:
// деление на число дней это то место, где ошибка не видна глазом (график останется
// красивым, но будет показывать размер группы дней вместо времени активности), поэтому
// логика лежит там, где её проверяет тест без монтирования полотна.
//
// В системе, а не в виджете: на этой раскладке стоят и активность платформы по часам
// аудита, и загрузка аудиторий по расписанию вуза (DESIGN_SYSTEM §12).

/**
 * Сетка 7×24. Форма структурная, без доменного типа: слой `shared` о домене не знает,
 * а обе панели отдают одно и то же — счётчики по дням недели и делитель.
 */
export interface DayHourGrid {
  /** cells[dow][hour], dow: 0 = понедельник. */
  cells: number[][]
  /**
   * Сколько таких дней недели покрывает сетка — делитель средних суток. Для журнала за
   * период это число календарных дат, для расписания недели — по единице на день.
   */
  days: number[]
}

/**
 * Разрез суточного профиля. Два ряда, а не семь: кривые отдельных дней недели в
 * этих данных почти совпадают и превращают график в клубок. Будни и выходные —
 * единственная пара с разной формой.
 */
export const DAY_GROUPS = [
  { key: 'weekdays', dows: [0, 1, 2, 3, 4] },
  { key: 'weekend', dows: [5, 6] },
] as const

/** Дни недели в порядке сетки: 0 = понедельник, как в `cells` с сервера. */
export const WEEKDAYS = [0, 1, 2, 3, 4, 5, 6] as const

/** Подписи часов: ось прореживает их сама, а в подсказке нужен полный «09:00». */
export const HOUR_LABELS = Array.from({ length: 24 }, (_, h) => `${String(h).padStart(2, '0')}:00`)

/**
 * Средние сутки группы дней: значение каждого часа, делённое на число ТАКИХ дней в
 * сетке. Сумма врала бы: будних дат в окне журнала впятеро больше, и ряд показывал бы
 * размер группы, а не время активности.
 *
 * Делитель считается не здесь: для журнала его даёт сервер (календарная арифметика в
 * его зоне), для расписания недели он равен единице на каждый день.
 */
export function averageDay(
  data: DayHourGrid | undefined,
  dows: readonly number[],
): { days: number; hours: number[] } {
  const days = dows.reduce((acc, d) => acc + (data?.days[d] ?? 0), 0)
  return {
    days,
    hours: Array.from({ length: 24 }, (_, h) => {
      const total = dows.reduce((acc, d) => acc + (data?.cells[d]?.[h] ?? 0), 0)
      return days ? total / days : 0
    }),
  }
}

/** Событий за одни сутки каждого дня недели — тот же средний день, но по одному dow. */
export function weekdayAverages(data: DayHourGrid | undefined): number[] {
  return WEEKDAYS.map((d) => averageDay(data, [d]).hours.reduce((a, b) => a + b, 0))
}
