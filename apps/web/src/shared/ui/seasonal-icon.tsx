import type { LucideIcon, LucideProps } from 'lucide-react'

/**
 * Иконка с праздничным знаком: к глифу добавляется снежинка, сам глиф не меняется.
 *
 * Почему это возможно без обёрток: lucide рендерит `children` ВНУТРЬ своего `<svg>`, сразу
 * после путей глифа. Поэтому знак живёт в той же иконке — DOM прежний, один `<svg>` с тем
 * же классом, и ни раскладка, ни выравнивание в строке не меняются. Обёртка-спан с
 * абсолютным позиционированием сломала бы и то и другое в трёх десятках мест.
 *
 * Показ отдан CSS (`globals.css`, «Праздничный знак на иконке»): знак нарисован всегда, но
 * виден только под `[data-season='new-year']`. Значит, включение и выключение праздника не
 * перерисовывает навигацию и не стоит ни одного ререндера.
 *
 * Где применять: иконки от 20 px — навигация, логотип, заголовочные знаки разделов. На
 * основном размере 16 px знак превращается в грязь на глифе и мешает читать саму иконку,
 * ради которой он и стоит.
 */
export function SeasonalIcon({ icon: Icon, ...rest }: { icon: LucideIcon } & LucideProps) {
  return (
    // aria-hidden по умолчанию: lucide сам его не ставит, когда у иконки есть children,
    // а знак — украшение, и в скринридере ему делать нечего.
    <Icon aria-hidden {...rest}>
      <g className="sh-ornament">
        {/* Подложка цветом поверхности: знак стоит ПЕРЕД глифом, а не поверх его линий —
            иначе на плотных иконках он читается как грязь. */}
        <circle className="sh-ornament-cut" cx="5.4" cy="5.4" r="3.7" />
        <path className="sh-ornament-mark" d="M5.4 2.6v5.6M3 4l4.8 2.8M3 6.8l4.8-2.8" />
      </g>
    </Icon>
  )
}
