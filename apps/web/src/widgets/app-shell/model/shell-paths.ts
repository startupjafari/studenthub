/**
 * Пути, которые рисуются БЕЗ оболочки приложения (сайдбар, нижняя навигация).
 *
 * Оболочка одна на всё приложение и живёт в корневом layout (PersistentShell): раньше её
 * рисовал layout каждой ролевой зоны, и переход между зонами — преподаватель открывает
 * свой профиль (`/profile` лежит в зоне студента), декан уходит из профиля обратно к себе —
 * менял один layout на другой. React пересоздавал сайдбар целиком, а на время загрузки
 * экран занимал корневой лоадер во всю высоту.
 *
 * Список — ровно те сегменты, у которых своей оболочки не было: вход и восстановление
 * доступа, публичные страницы по ссылке (проверка документа, резюме, приглашение в чат),
 * заявка вуза, регистрация работодателя, офлайн-фолбэк PWA и витрина разработчика.
 * Новая публичная страница вне оболочки обязана попасть сюда; список закреплён тестом.
 */
const SHELL_FREE: readonly string[] = [
  '/login',
  '/register',
  '/forgot-password',
  '/reset-password',
  '/setup-2fa',
  '/offline',
  '/demo',
  '/legal',
  '/verify',
  '/r/resume',
  '/c',
  '/qr',
  '/join-chat',
  '/employer/signup',
  '/employer/verify',
  // Каталог `app/%5Fdev`: Next исключает из роутинга папки на `_`, адрес — `/_dev`.
  '/_dev',
]

/**
 * Только сам адрес, без вложенных: `/r` — публичная страница, а `/r/<код>` (переход по
 * короткой ссылке вошедшего) живёт в зоне студента, внутри оболочки.
 */
const SHELL_FREE_EXACT: readonly string[] = ['/r']

/** Рисуется ли путь внутри оболочки приложения. */
export function isShellPath(pathname: string): boolean {
  if (SHELL_FREE_EXACT.includes(pathname)) return false
  return !SHELL_FREE.some((p) => pathname === p || pathname.startsWith(`${p}/`))
}
