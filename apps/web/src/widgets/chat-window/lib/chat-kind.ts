import type { ChatTypeValue } from '../../../entities/chat'

/**
 * Есть ли у чата пункт «Удалить» (F-F17).
 *
 * Только у личного чата (скрыть у себя) и пользовательской группы (выйти, а владельцу —
 * удалить её). Официальный чат вернулся бы сам — его заводит сервер, — а «Сохранённые»
 * удаление стирало вместе с заметками. Такие чаты сервер на «удалить» теперь только
 * скрывает, и пункт с этим названием обещал бы больше, чем делает: для них в меню остаются
 * «Очистить историю» и «Архив».
 */
export function canDeleteChat(type: ChatTypeValue): boolean {
  return type === 'PRIVATE' || type === 'GROUP'
}
