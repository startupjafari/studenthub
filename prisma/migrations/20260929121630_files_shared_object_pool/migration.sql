-- Пара (bucket, key) перестаёт быть уникальной: несколько записей files могут ссылаться на
-- один объект хранилища. Нужно для общего пула медиа у сида — иначе каждая карточка галереи
-- это отдельный объект в MinIO, то есть сотни гигабайт на большом прогоне.
--
-- Блокировки: DROP INDEX и CREATE INDEX берут блокировку на files на время выполнения. Индекс
-- строится по двум коротким текстовым колонкам, на боевой таблице это секунды. CONCURRENTLY не
-- используется намеренно: Prisma гоняет миграцию в транзакции, а там CONCURRENTLY недопустим.

-- DropIndex
DROP INDEX "files_bucket_key_key";

-- CreateIndex
CREATE INDEX "files_bucket_key_idx" ON "files"("bucket", "key");
