-- Язык интерфейса и исходящих писем у пользователя.
-- Аддитивно: колонка со значением по умолчанию, существующие строки получают 'ru' —
-- ровно то, на чём им и писали до сих пор, то есть поведение для них не меняется.
ALTER TABLE "users" ADD COLUMN     "locale" TEXT NOT NULL DEFAULT 'ru';

-- Ключ сообщения и параметры у уведомления — чтобы текст можно было отрисовать заново
-- на другом языке. NULL у всех существующих строк: ключ задним числом не выдумывается,
-- такие уведомления клиент показывает из title/body как есть.
ALTER TABLE "notifications" ADD COLUMN     "title_key" TEXT,
ADD COLUMN     "body_key" TEXT,
ADD COLUMN     "params" JSONB;
