-- Индекс под фактический порядок сортировки ленты (docs/PERF_BASELINE.md).
--
-- Лента сортирует `pinned_at DESC NULLS LAST, priority DESC, created_at DESC, id DESC`.
-- Прежний индекс был по возрастанию, обратный проход по нему даёт DESC NULLS FIRST —
-- порядок не совпадал, и Postgres читал таблицу постов целиком и сортировал: на 90 тыс.
-- постов 23 мс и 1986 буферов на каждую страницу ленты, с ростом таблицы линейно хуже.
--
-- SQL написан руками, а не сгенерирован: `NULLS LAST` в @@index Prisma принимает, но в
-- DDL теряет (проверено `migrate diff` на 6.19.3), а DESC без него означает NULLS FIRST —
-- то есть незакреплённые посты оказались бы выше закреплённых. Порядок NULL Prisma не
-- моделирует вовсе, поэтому дрейфа схемы рукописный вариант не даёт.
--
-- Замер на 90 тыс. постов (та же форма запроса, что у `feed`):
--   было  — Parallel Seq Scan + Sort, 23.4 мс, 1986 буферов
--   стало — Index Scan с ранней остановкой, 0.04 мс, 19 буферов
-- Выигрыш не только в скорости: индексный проход останавливается на 21-й строке, поэтому
-- стоимость страницы перестаёт зависеть от размера таблицы.
--
-- Старый индекс снимается как полностью перекрытый: по pinned_at по возрастанию в коде не
-- сортирует никто, а лишний индекс оплачивается на каждой записи поста.
--
-- CREATE INDEX (без CONCURRENTLY) держит SHARE на `posts` и блокирует запись на время
-- построения: Prisma выполняет миграцию в транзакции, а CONCURRENTLY внутри транзакции
-- запрещён. На нынешнем объёме это доли секунды.
DROP INDEX "posts_pinned_at_priority_created_at_idx";

CREATE INDEX "posts_pinned_at_priority_created_at_id_idx"
  ON "posts" ("pinned_at" DESC NULLS LAST, "priority" DESC, "created_at" DESC, "id" DESC);
