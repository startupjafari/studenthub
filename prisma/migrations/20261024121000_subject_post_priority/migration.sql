-- Пост преподавателя «по предмету» (SUBJECT) стоял в ленте ниже студенческих постов в
-- группу: приоритет считался как 25 + 2 = 27 против 30 у студента (docs/PROJECT.md §3.3 —
-- посты преподавателей выше постов студентов). База SUBJECT поднята до 29, новые посты
-- получают 31; уже опубликованным пересчитываем значение той же формулой.
--
-- Условие на прежнее значение 27: приоритет пишет только сервис при создании, а строки с
-- другим числом (данные сида, ручные правки) — не его расчёт, их не трогаем.
UPDATE "posts"
SET "priority" = 31
WHERE "audience" = 'SUBJECT' AND "priority" = 27;
