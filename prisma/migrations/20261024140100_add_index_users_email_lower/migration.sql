-- Индекс по lower(email) под поиск email без учёта регистра.
--
-- Вход, сброс пароля и проверка «адрес занят» при регистрации по инвайту сначала ищут точное
-- совпадение, а не найдя — запасным путём `LOWER(email) IN (LOWER($1))` (строки, записанные до
-- нормализации email в нижний регистр). Уникальный индекс по email этому условию не помогает,
-- и каждый вход с несуществующим адресом и каждая регистрация читали таблицу users целиком.
--
-- SQL написан руками: Prisma индексы по выражению в схеме не моделирует (см. комментарий у
-- модели User), а миграции и сравнение схемы такие индексы пропускают.
--
-- Не UNIQUE: до нормализации могли завестись `Ivanov@…` и `ivanov@…` разными учётками,
-- сервис это различает (singleEmailOwner), и уникальность здесь уронила бы миграцию.
--
-- CREATE INDEX без CONCURRENTLY: Prisma выполняет миграцию в транзакции.

-- CreateIndex
CREATE INDEX "users_email_lower_idx" ON "users"(lower("email"));
