/** Текст поста: собирается из фрагментов, длина случайная. */
export function postText(random) {
  if (random.chance(0.25)) return random.pick(POST_LIFE)
  const [opener, grammaticalCase] = random.pick(POST_FRAMES)
  const parts = [
    `${opener} ${random.pick(TOPICS_BY_CASE[grammaticalCase])}.`,
    random.pick(POST_DETAILS),
    random.chance(0.4) ? random.pick(POST_TAILS) : '',
  ]
  return parts.filter(Boolean).join(' ')
}

