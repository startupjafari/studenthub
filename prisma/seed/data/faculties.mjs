// Факультеты конкретного вуза: первые пять есть почти всегда (без них вуз выглядит
// неполным), дальше добор по индексу вуза — так профили вузов различаются.
export function facultiesFor(index, count) {
  const base = FACULTY_TEMPLATES.slice(0, 5)
  const extra = FACULTY_TEMPLATES.slice(5)
  const taken = [...base]
  for (let i = 0; taken.length < count && i < extra.length; i += 1) {
    taken.push(extra[(index + i) % extra.length])
  }
  return taken.slice(0, count)
}
