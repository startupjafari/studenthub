// Транслитерация для username/email: латиница из русского имени.
const TRANSLIT = {
  а:'a',б:'b',в:'v',г:'g',д:'d',е:'e',ё:'e',ж:'zh',з:'z',и:'i',й:'i',к:'k',л:'l',м:'m',н:'n',о:'o',п:'p',р:'r',с:'s',т:'t',у:'u',ф:'f',х:'h',ц:'c',ч:'ch',ш:'sh',щ:'sch',ъ:'',ы:'y',ь:'',э:'e',ю:'yu',я:'ya',
  ә:'a',ғ:'g',қ:'q',ң:'n',ө:'o',ұ:'u',ү:'u',һ:'h',і:'i',
} // prettier-ignore

export function translit(value) {
  return value
    .toLowerCase()
    .split('')
    .map((ch) => TRANSLIT[ch] ?? (/[a-z0-9]/.test(ch) ? ch : ''))
    .join('')
}

// Человек: имя, фамилия, отчество, пол. index задаёт пол (чётные — женщины),
// чтобы соотношение было ровным, а не случайным перекосом.
export function person(index, random) {
  const female = index % 2 === 0
  const first = random.pick(female ? FEMALE_NAMES : MALE_NAMES)
  const surnameM = random.pick(SURNAMES_M)
  const root = random.pick(PATRONYMIC_ROOTS)
  return {
    firstName: first,
    lastName: female ? `${surnameM}а` : surnameM,
    middleName: female ? `${root}овна` : `${root}ович`,
    gender: female ? 'FEMALE' : 'MALE',
  }
}

// Реальные мобильные префиксы операторов Казахстана: телефон в профиле должен
// проходить те же проверки формата, что и введённый руками.
const PHONE_PREFIXES = ['700','701','702','705','706','707','708','747','771','775','776','777','778'] // prettier-ignore

export function phone(random) {
  const pad2 = (n) => String(n).padStart(2, '0')
  return `+7 (${random.pick(PHONE_PREFIXES)}) ${random.randInt(100, 999)}-${pad2(
    random.randInt(0, 99),
  )}-${pad2(random.randInt(0, 99))}`
}
